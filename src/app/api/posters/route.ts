import { NextResponse } from 'next/server';
import { getPosters, addPoster } from '@/lib/db';
import { parseImageBuffer, formatBytes, calculateAspectRatio } from '@/lib/image-meta';
import path from 'path';
import fs from 'fs';

export async function GET(request: Request) {
  try {
    const { searchParams } = new URL(request.url);
    const category = searchParams.get('category') || undefined;
    const language = searchParams.get('language') || undefined;
    const search = searchParams.get('q') || searchParams.get('search') || undefined;

    const posters = getPosters({ category, language, search });
    return NextResponse.json(posters, {
      headers: {
        'Cache-Control': 'public, max-age=30, stale-while-revalidate=120'
      }
    });
  } catch (error: any) {
    return NextResponse.json({ error: error.message }, { status: 500 });
  }
}

export async function POST(request: Request) {
  try {
    const contentType = request.headers.get('content-type') || '';
    const uploadDir = path.join(process.cwd(), 'public', 'uploads', 'posters');
    if (!fs.existsSync(uploadDir)) {
      fs.mkdirSync(uploadDir, { recursive: true });
    }

    // 1. Multipart Form Data (Direct File Upload)
    if (contentType.includes('multipart/form-data')) {
      const formData = await request.formData();
      const file = formData.get('file') as File | null;
      const thumbnailFile = formData.get('thumbnail') as File | null;
      const largeFile = formData.get('large') as File | null;

      const title = (formData.get('title') as string) || '';
      const description = (formData.get('description') as string) || '';
      const event_name = (formData.get('event_name') as string) || '';
      const event_date = (formData.get('event_date') as string) || '';
      const event_time = (formData.get('event_time') as string) || '';
      const location = (formData.get('location') as string) || '';
      const category = (formData.get('category') as string) || 'Special Event';
      const language = (formData.get('language') as string) || 'Telugu + English';
      const bible_reference = (formData.get('bible_reference') as string) || '';
      const speaker = (formData.get('speaker') as string) || '';
      const contact_info = (formData.get('contact_info') as string) || '';

      // Client-provided dimensions (if any)
      const clientWidth = formData.get('width') ? Number(formData.get('width')) : undefined;
      const clientHeight = formData.get('height') ? Number(formData.get('height')) : undefined;
      const clientAspectRatio = (formData.get('aspect_ratio') as string) || undefined;
      const clientFileType = (formData.get('file_type') as string) || undefined;
      const clientFileSize = (formData.get('file_size') as string) || undefined;

      let imageUrl = (formData.get('image_url') as string) || '';
      let largeUrl: string | undefined = undefined;
      let thumbnailUrl: string | undefined = undefined;
      let imageData: string | undefined = undefined;

      let detectedWidth = clientWidth;
      let detectedHeight = clientHeight;
      let detectedAspectRatio = clientAspectRatio;
      let detectedFileType = clientFileType;
      let detectedFileSize = clientFileSize;
      let detectedFileSizeBytes = file ? file.size : undefined;

      if (file && file.size > 0) {
        const bytes = await file.arrayBuffer();
        const buffer = Buffer.from(bytes);
        const parsed = parseImageBuffer(buffer);

        if (parsed) {
          detectedWidth = detectedWidth || parsed.width;
          detectedHeight = detectedHeight || parsed.height;
          detectedAspectRatio = detectedAspectRatio || parsed.aspect_ratio;
          detectedFileType = detectedFileType || parsed.file_type;
          detectedFileSize = detectedFileSize || parsed.file_size;
          detectedFileSizeBytes = buffer.length;
        }

        const ext = path.extname(file.name || 'poster.jpg') || (detectedFileType === 'PNG' ? '.png' : detectedFileType === 'WebP' ? '.webp' : '.jpg');
        const timestamp = Date.now();
        const rand = Math.random().toString(36).substring(2, 7);

        // Store ORIGINAL image at 100% full quality without any compression or alteration
        const origFilename = `poster-orig-${timestamp}-${rand}${ext}`;
        fs.writeFileSync(path.join(uploadDir, origFilename), buffer);
        imageUrl = `/uploads/posters/${origFilename}`;

        // Handle separate LARGE display version if generated by client
        if (largeFile && largeFile.size > 0) {
          const largeBytes = await largeFile.arrayBuffer();
          const largeFilename = `poster-large-${timestamp}-${rand}.webp`;
          fs.writeFileSync(path.join(uploadDir, largeFilename), Buffer.from(largeBytes));
          largeUrl = `/uploads/posters/${largeFilename}`;
        } else {
          largeUrl = imageUrl;
        }

        // Handle separate THUMBNAIL version if generated by client
        if (thumbnailFile && thumbnailFile.size > 0) {
          const thumbBytes = await thumbnailFile.arrayBuffer();
          const thumbFilename = `poster-thumb-${timestamp}-${rand}.webp`;
          fs.writeFileSync(path.join(uploadDir, thumbFilename), Buffer.from(thumbBytes));
          thumbnailUrl = `/uploads/posters/${thumbFilename}`;
        } else {
          thumbnailUrl = largeUrl || imageUrl;
        }

        // Base64 durability backup if under 3MB
        if (buffer.length < 3 * 1024 * 1024) {
          const mime = file.type || (ext === '.png' ? 'image/png' : ext === '.webp' ? 'image/webp' : 'image/jpeg');
          imageData = `data:${mime};base64,${buffer.toString('base64')}`;
        }
      }

      if (!imageUrl && !imageData) {
        return NextResponse.json({ error: 'Poster image is required' }, { status: 400 });
      }

      const id = addPoster({
        image_url: imageUrl,
        large_url: largeUrl || imageUrl,
        thumbnail_url: thumbnailUrl || largeUrl || imageUrl,
        image_data: imageData,
        title,
        description,
        event_name,
        event_date,
        event_time,
        location,
        category,
        language,
        bible_reference,
        speaker,
        contact_info,
        width: detectedWidth,
        height: detectedHeight,
        aspect_ratio: detectedAspectRatio || (detectedWidth && detectedHeight ? calculateAspectRatio(detectedWidth, detectedHeight) : undefined),
        file_type: detectedFileType || (imageUrl.endsWith('.png') ? 'PNG' : imageUrl.endsWith('.webp') ? 'WebP' : 'JPEG'),
        file_size: detectedFileSize || (detectedFileSizeBytes ? formatBytes(detectedFileSizeBytes) : undefined),
        file_size_bytes: detectedFileSizeBytes
      });

      return NextResponse.json({ 
        success: true, 
        id, 
        image_url: imageUrl,
        large_url: largeUrl || imageUrl,
        thumbnail_url: thumbnailUrl || largeUrl || imageUrl
      }, { status: 201 });
    }

    // 2. JSON Payload
    const body = await request.json();
    let {
      image_url,
      large_url,
      thumbnail_url,
      image_data,
      image,
      title,
      description,
      event_name,
      event_date,
      event_time,
      location,
      category,
      language,
      bible_reference,
      speaker,
      contact_info,
      width,
      height,
      aspect_ratio,
      file_type,
      file_size,
      file_size_bytes
    } = body;

    if (!image_data && image && image.startsWith('data:')) {
      image_data = image;
    } else if (!image_url && image && !image.startsWith('data:')) {
      image_url = image;
    }

    // If base64 data provided, save as physical file to disk
    if (image_data && (!image_url || image_url.startsWith('data:'))) {
      try {
        const matches = image_data.match(/^data:([A-Za-z-+\/]+);base64,(.+)$/);
        if (matches && matches.length === 3) {
          const mime = matches[1];
          const ext = mime.includes('png') ? '.png' : mime.includes('webp') ? '.webp' : '.jpg';
          const buffer = Buffer.from(matches[2], 'base64');
          const parsed = parseImageBuffer(buffer);

          if (parsed) {
            width = width || parsed.width;
            height = height || parsed.height;
            aspect_ratio = aspect_ratio || parsed.aspect_ratio;
            file_type = file_type || parsed.file_type;
            file_size = file_size || parsed.file_size;
            file_size_bytes = file_size_bytes || parsed.file_size_bytes;
          }

          const filename = `poster-orig-${Date.now()}-${Math.random().toString(36).substring(2, 7)}${ext}`;
          fs.writeFileSync(path.join(uploadDir, filename), buffer);
          image_url = `/uploads/posters/${filename}`;
        }
      } catch (e) {
        image_url = image_data;
      }
    }

    if (!image_url && !image_data) {
      return NextResponse.json({ error: 'Poster image is required' }, { status: 400 });
    }

    const id = addPoster({
      image_url: image_url || image_data,
      large_url: large_url || image_url || image_data,
      thumbnail_url: thumbnail_url || large_url || image_url || image_data,
      image_data,
      title,
      description,
      event_name,
      event_date,
      event_time,
      location,
      category: category || 'Special Event',
      language: language || 'Telugu + English',
      bible_reference,
      speaker,
      contact_info,
      width,
      height,
      aspect_ratio: aspect_ratio || (width && height ? calculateAspectRatio(width, height) : undefined),
      file_type: file_type || 'JPEG',
      file_size: file_size || (file_size_bytes ? formatBytes(file_size_bytes) : undefined),
      file_size_bytes
    });

    return NextResponse.json({ 
      success: true, 
      id, 
      image_url,
      large_url: large_url || image_url,
      thumbnail_url: thumbnail_url || large_url || image_url
    }, { status: 201 });
  } catch (error: any) {
    return NextResponse.json({ error: error.message }, { status: 500 });
  }
}
